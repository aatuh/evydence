#!/usr/bin/env python3
"""Generate and validate Evydence persistence decomposition inventory."""

from __future__ import annotations

import argparse
import difflib
import re
import sys
from dataclasses import dataclass
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[1]
APP_ROOT = REPO_ROOT / "internal" / "app"
OUTPUT = REPO_ROOT / "docs" / "reference" / "persistence-decomposition.md"

FUNC_RE = re.compile(r"^func\s+(?:\([^)]*\)\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*\(")
CRITICAL_CALLS = {"persistCriticalLocked", "persistCriticalStateLocked"}
RELEASE_CALLS = {
    "persistReleaseLedgerLocked",
    "persistReleaseLedgerStateLocked",
    "persistReleaseLedgerWithOutboxLocked",
}
BROAD_CALLS = {"persistLocked"}
PERSISTENCE_CALLS = (*sorted(CRITICAL_CALLS), *sorted(RELEASE_CALLS), *sorted(BROAD_CALLS))


@dataclass(frozen=True)
class PersistCall:
    file: str
    function: str
    call: str
    production: bool


FAMILY_BY_FILE = {
    "builds.go": "build provenance",
    "controls.go": "controls",
    "enterprise.go": "enterprise identity and retention",
    "future_extensions.go": "future extensions and generated reports",
    "governance_packages.go": "governance, packages, and package reports",
    "identity_service.go": "identity",
    "idempotency.go": "identity and idempotency",
    "implementation_increments.go": "release extensions, source, and deployment",
    "integrity_runtime.go": "integrity and operations",
    "ledger.go": "release ledger and signing",
    "package_context_adapter.go": "package and reporting",
    "risk_context_adapter.go": "vulnerability decisions and governance",
    "tenant_bootstrap_service.go": "tenant bootstrap",
    "verification_context_adapter.go": "verification and signing",
    "risk_workflows.go": "risk and security workflows",
    "state.go": "persistence helpers",
    "vex.go": "VEX and vulnerability decisions",
}


def collect_calls() -> list[PersistCall]:
    calls: list[PersistCall] = []
    for path in sorted(APP_ROOT.glob("*.go")):
        if path.name.endswith("_test.go") or path.name == "state.go":
            continue
        functions: list[tuple[str, list[str]]] = []
        current = "package-scope"
        body: list[str] = []
        for line in path.read_text(encoding="utf-8").splitlines():
            match = FUNC_RE.match(line)
            if match:
                functions.append((current, body))
                current, body = match.group(1), []
                continue
            body.append(line)
        functions.append((current, body))
        for function, body in functions:
            focused_uow = "l.unitOfWork != nil" in "\n".join(body) and "l.ExecuteUnitOfWork" in "\n".join(body)
            for line in body:
                for call in PERSISTENCE_CALLS:
                    if f".{call}(ctx" in line or f" {call}(ctx" in line:
                        calls.append(PersistCall(path.name, function, call, call not in BROAD_CALLS or not focused_uow))
    return calls


def render_table(calls: list[PersistCall]) -> list[str]:
    if not calls:
        return ["| Family | File | Function | Call |", "| --- | --- | --- | --- |", "| none | none | none | none |"]
    rows = ["| Family | File | Function | Call |", "| --- | --- | --- | --- |"]
    for call in sorted(calls, key=lambda c: (FAMILY_BY_FILE.get(c.file, c.file), c.file, c.function, c.call)):
        rows.append(
            "| "
            + " | ".join(
                [
                    FAMILY_BY_FILE.get(call.file, "unclassified"),
                    f"`internal/app/{call.file}`",
                    f"`{call.function}`",
                    f"`{call.call}`",
                ]
            )
            + " |"
        )
    return rows


def render(calls: list[PersistCall]) -> str:
    critical = [c for c in calls if c.call in CRITICAL_CALLS]
    release = [c for c in calls if c.call in RELEASE_CALLS]
    broad = [c for c in calls if c.call in BROAD_CALLS and c.production]
    compatibility_broad = [c for c in calls if c.call in BROAD_CALLS and not c.production]
    lines: list[str] = [
        "# Persistence Decomposition Inventory",
        "",
        "This reference is generated by `scripts/persistence_decomposition_inventory.py`.",
        "Update it with `scripts/persistence_decomposition_inventory.py --write` after persistence call sites change.",
        "",
        "Purpose: keep production repository paths and historical aggregate-persistence retirement inspectable.",
        "",
        "## Current Production Contract",
        "",
        "- Production PostgreSQL uses relational-only storage and focused transaction/command/query ports, without constructing an application Ledger.",
        "- Production writes do not create or update the compatibility `ledger_state` snapshot row.",
        "- Former Ledger maps, locks, snapshot publication, persistence forwarding and replay fallbacks compile only as historical test oracles.",
        "- Native writes use caller-owned repositories through `ExecuteUnitOfWork` and `IdempotencyUnitOfWork`; shared persistence DTOs and explicit storage utilities are not an aggregate command surface.",
        "- The tables below inspect non-test source for retired helper calls. A new call is a retirement regression, not a supported broad-write fallback.",
        "- One API writer replica remains the supported production candidate topology until every write family has focused repository paths or a reviewed optimistic-concurrency design.",
        "",
        "## Focused Critical Mutations",
        "",
        *render_table(critical),
        "",
        "## Focused Release And Evidence Mutations",
        "",
        *render_table(release),
        "",
        "## Remaining Broad Relational-State Mutations",
        "",
        *render_table(broad),
        "",
        "## Compatibility-Only Broad Fallbacks",
        "",
        "No supported runtime installs an aggregate fallback. Historical fallback implementations remain in test-only characterization and are excluded from this source inventory.",
        "",
        *render_table(compatibility_broad),
        "",
        "## Next Decomposition Order",
        "",
        "1. Run the required full, race and production/live gates before closing EVY-906; source retirement alone is not their evidence.",
        "2. Keep native command/query ownership and bounded repository reads explicit as later tickets evolve the contexts.",
        "3. Retain only deliberate persistence/import/export utilities; do not restore the retired Ledger command, cache or snapshot surface.",
        "",
        "## Regression Checks",
        "",
        "- `go test ./internal/app -run TestLegacyPackageGeneratorsAreAbsentFromProduction` enforces aggregate type/constructor/helper retirement in non-test source.",
        "- `go test ./internal/app -run TestRelationalStateStore` characterizes historical persistence behavior in test-only oracles, not a production broad-write path.",
        "- `go test ./internal/adapters/postgres -run 'TestApply(Critical|ReleaseLedger)Mutation'` proves focused mutations write relational tables and avoid the compatibility snapshot row.",
        "- `make persistence-decomposition-check` regenerates this inventory and fails when the documented call-site map drifts.",
        "",
        "## Limitations",
        "",
        "This inventory is a repository-local decomposition map. It is not evidence of legal compliance, certification, complete operational hardening, or multi-writer API safety.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="write generated inventory to docs/reference/persistence-decomposition.md")
    parser.add_argument("--check", action="store_true", help="fail if the generated inventory differs from the committed file")
    args = parser.parse_args()
    body = render(collect_calls())
    if args.write:
        OUTPUT.write_text(body, encoding="utf-8")
        return 0
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != body:
            diff = difflib.unified_diff(
                current.splitlines(),
                body.splitlines(),
                fromfile=str(OUTPUT),
                tofile="generated",
                lineterm="",
            )
            print("\n".join(diff), file=sys.stderr)
            return 1
        return 0
    print(body)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
